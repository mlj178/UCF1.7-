def translate_field_by_words(field_name):
    """根据单词翻译字段名"""
    # 先检查是否有完整翻译
    if field_name in word_translations:
        return word_translations[field_name]
    
    # 拆分驼峰命名
    parts = re.findall(r'[A-Z]?[a-z]+|[A-Z]+(?=[A-Z][a-z]|[0-9]|\b)|\d+', field_name)
    
    translations = []
    for part in parts:
        if part.lower() in word_translations:
            translations.append(word_translations[part.lower()])
        else:
            translations.append(part)
    
    return ''.join(translations) if translations else field_name

def process_file1(input_path):
    """处理文件1 - 完整版可视化.html"""
    with open(input_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # 匹配fields数组中的字段，格式: "fieldName : type"
    def replace_field_no_translation(match):
        indent = match.group(1)
        field_name = match.group(2)
        field_type = match.group(3)
        # 如果已经有翻译了（包含括号），跳过
        if '(' in field_name or ')' in field_name:
            return match.group(0)
        translation = translate_field_by_words(field_name)
        return f'{indent}"{field_name} ({translation}) : {field_type}"'
    
    # 只匹配fields数组内的字段定义
    content = re.sub(
        r'^(\s*)"(\w+)\s*:\s*([^"]+)"\s*$',
        replace_field_no_translation,
        content,
        flags=re.MULTILINE
    )
    
    with open(input_path, 'w', encoding='utf-8') as f:
        f.write(content)
    
    print(f'文件1处理完成')

def process_file2(input_path):
    """处理文件2 - 核心类详细定义.html"""
    with open(input_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # 处理字段 - <div class="field-item">...</div>
    def replace_field_div(match):
        div_content = match.group(0)
        # 如果已经有翻译了，跳过
        if 'field-cn' in div_content:
            return div_content
        # 提取字段名
        field_match = re.search(r'</span>\s*(\w+)\s*</div>', div_content)
        if field_match:
            field_name = field_match.group(1)
            translation = translate_field_by_words(field_name)
            # 在字段名后添加中文翻译
            new_div = div_content.replace(f'{field_name}</div>', f'{field_name} <span class="field-cn">({translation})</span></div>')
            return new_div
        return div_content
    
    content = re.sub(r'<div class="field-item">.*?</div>', replace_field_div, content, flags=re.DOTALL)
    
    with open(input_path, 'w', encoding='utf-8') as f:
        f.write(content)
    
    print(f'文件2处理完成')

